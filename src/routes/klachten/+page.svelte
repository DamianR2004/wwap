<section>
  <h2>Vertrouwenspersoon</h2>
  <p>
    Heb je te maken met ongewenst gedrag, zoals pesten, agressie, discriminatie,
    seksuele intimidatie of bedreiging? Dan kun je terecht bij de
    vertrouwenspersoon van WWAP. Zij luistert naar je verhaal, denkt met je mee
    en helpt je desgewenst bij de stappen naar een officiële klacht.
  </p>
</section>

<section>
  <h2>Vertrouwelijkheid</h2>
  <p>
    WWAP behandelt je klacht vertrouwelijk. Het indienen van een klacht heeft geen gevolgen 
    voor de begeleiding of ondersteuning die je van ons ontvangt.
  </p>
