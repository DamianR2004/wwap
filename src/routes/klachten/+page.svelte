<section>
  <h1>Klachten</h1>
  <p>
    Bij WWAP vinden we het belangrijk dat je je gehoord, serieus genomen en
    veilig voelt. Ben je niet tevreden over de begeleiding, een afspraak, een
    medewerker of de manier waarop iets is gegaan? Dan kijken we daar graag
    samen met jou naar.
  </p>
</section>

<section>
  <h2>In drie stappen</h2>
  <ol>
    <li>
      <p>
        Bespreek je klacht met de persoon over wie of waarover de klacht gaat,
        bijvoorbeeld je begeleider, mentor, zorgcoördinator of teamleider. Een
        gesprek kan vaak al helpen. Je mag je daarbij altijd laten ondersteunen
        door iemand die je vertrouwt. WWAP reageert binnen vijf werkdagen op je
        melding.
      </p>
    </li>
    <li>
      <p>
        Helpt het gesprek niet of vind je het lastig om je klacht rechtstreeks
        te bespreken? Neem dan contact op met het managementteam van WWAP. Je
        ontvangt binnen vijf werkdagen een ontvangstbevestiging. WWAP streeft
        ernaar om binnen twee weken samen met jou tot een oplossing te komen.
      </p>
    </li>
    <li>
      <p>
        Komen we er samen niet uit? Dan kun je een formele klacht indienen bij
        Klachtenportaal Zorg, de onafhankelijke klachteninstantie waarbij WWAP
        is aangesloten volgens de Wet kwaliteit, klachten en geschillen zorg
        (Wkkgz). Dit kan via <a href="https://www.klachtenportaalzorg.nl" target="_blank" rel="noopener noreferrer">www.klachtenportaalzorg.nl</a> of <a href="mailto:info@klachtenportaalzorg.nl">info@klachtenportaalzorg.nl</a>.
        Je ontvangt binnen vijf werkdagen een ontvangstbevestiging. De behandeling
        duurt daarna maximaal zes weken en kan eenmaal met vier weken worden verlengd.
      </p>
    </li>
  </ol>
  <p>
    Ben je niet tevreden over de uitkomst van je klacht? Dan kun je terecht bij
    de Geschillencommissie Zorginstellingen, die is verbonden aan
    Klachtenportaal Zorg.
  </p>
</section>

