<section>
  <h1>Partners</h1>

  <p>
    Geen enkele organisatie kan een jongere op ieder levensgebied ondersteunen.
    Daarom werken we nauw samen met gemeenten, verwijzers en andere
    organisaties. We delen wat nodig is, stemmen verantwoordelijkheden af en
    houden steeds het belang van de jongere voor ogen.
  </p>
</section>

<section>
  <h2>Voor gemeenten en verwijzers</h2>

  <p>
    Voor gemeenten en verwijzers willen we een partner zijn die bereikbaar is,
    eerlijk communiceert en ook bij ingewikkelde vragen blijft meedenken. We
    kijken zorgvuldig of onze begeleiding past bij de jongere en bespreken
    verwachtingen vooraf. Tijdens de begeleiding houden we de lijnen kort en
    signaleren we tijdig wanneer iets verandert.
  </p>
</section>

<section>
  <h2>Voor samenwerkingspartners</h2>

  <p>
    We werken samen met zorg- en welzijnsorganisaties in de regio wanneer een
    jongere aanvullende ondersteuning nodig heeft of een vraag buiten ons eigen
    aanbod valt. Door goed af te stemmen, kunnen verschillende vormen van
    ondersteuning beter op elkaar aansluiten.
  </p>
</section>

