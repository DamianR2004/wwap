<section>
  <h1>Privacy</h1>

  <p>
    WWAP B.V. (‘WWAP’, ‘wij’) gaat zorgvuldig om met persoonsgegevens en houdt
    zich aan de Algemene verordening gegevensbescherming (AVG).
  </p>
</section>

<section>
  <h2>Welke gegevens verwerken wij en waarom</h2>

  <p>
    Via deze website verwerken we de gegevens die je zelf invult, bijvoorbeeld
    via het contactformulier. Dit kunnen je naam, e-mailadres, telefoonnummer en
    de inhoud van je bericht zijn. We gebruiken deze gegevens om contact met je
    op te nemen en je vraag te beantwoorden.
  </p>
  <p>
    Als je bij ons woont of begeleiding krijgt, verwerken we daarnaast andere
    persoonsgegevens en bijzondere persoonsgegevens, waaronder
    gezondheidsgegevens, die nodig zijn voor je begeleiding. Dit gebeurt niet
    via deze website, maar binnen onze reguliere zorg- en begeleidingsprocessen
    en met de zorgvuldigheid die daarbij hoort.
  </p>
</section>

<section>
  <h2>Bewaartermijn</h2>

  <p>
    We bewaren persoonsgegevens niet langer dan nodig is voor het doel waarvoor
    ze zijn verzameld, tenzij de wet een langere bewaartermijn voorschrijft.
  </p>
</section>

<section>
  <h2>Delen met derden</h2>

  <p>
    We delen persoonsgegevens alleen met derden als dat nodig is voor onze
    dienstverlening, bijvoorbeeld met een gemeente of verwijzer bij een
    aanmelding. Ook kunnen we gegevens delen als we daartoe wettelijk verplicht
    zijn of als jij daarvoor toestemming hebt gegeven.
  </p>
</section>

<section>
  <h2>Jouw rechten</h2>

  <p>
    Je hebt het recht om je persoonsgegevens in te zien, te laten corrigeren of
    te laten verwijderen. Je kunt ook bezwaar maken tegen de verwerking van je
    gegevens of vragen om je gegevens aan jou of aan een andere partij over te
    dragen. Neem hiervoor contact met ons op via <a href="mailto:info@wwap.nl">info@wwap.nl</a>.
  </p>

  <p>
    Ben je niet tevreden over de manier waarop we met je gegevens omgaan? Dan
    kun je een klacht indienen bij de Autoriteit Persoonsgegevens.
  </p>
</section>
