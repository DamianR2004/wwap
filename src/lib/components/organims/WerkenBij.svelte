<section>
  <h2>Wie wij zijn</h2>

  <p>
    WWAP is een zorgorganisatie in de regio Ede en Wageningen. We bieden
    beschermd wonen, beschermd thuis en ambulante begeleiding. Onze teams zijn
    overzichtelijk en de lijnen zijn kort. Collega’s kennen elkaar, overleggen
    gemakkelijk en dragen samen verantwoordelijkheid voor goede begeleiding.
  </p>
</section>

<section>
  <h2>Hoe wij werken</h2>

  <p>
    Als begeleider sta je naast de jongere. Je denkt mee, biedt structuur en
    spreekt aan wanneer dat nodig is. Tegelijkertijd neem je niet over wat
    iemand zelf kan.
  </p>

  <p>
    Geen jongere en geen dag is hetzelfde. Soms werk je aan praktische zaken,
    zoals administratie, dagstructuur, opleiding of werk. Op andere momenten
    gaat het over spanning, sociale contacten of het voorkomen van terugval. Je
    werkt vanuit een begeleidingsplan, maar houdt altijd oog voor wat er op dat
    moment speelt.
  </p>
</section>

<section>
  <h2>Wat werken bij WWAP van je vraagt</h2>

  <p>
    Je kunt zelfstandig beslissingen nemen en weet wanneer je een collega moet
    betrekken. Je maakt gemakkelijk contact, blijft duidelijk en kunt omgaan met
    situaties die anders verlopen dan verwacht. Je reflecteert op je eigen
    handelen en werkt zorgvuldig samen met jongeren, collega’s, het netwerk en
    verwijzers.
  </p>
</section>

<section>
  <h2>Wat je van WWAP kunt verwachten</h2>

  <p>
    Je komt terecht in een betrokken team waarin collega’s elkaar kennen, met
    elkaar meedenken en elkaar aanspreken. Je krijgt ruimte om je professionele
    oordeel te gebruiken en initiatief te nemen, binnen de gezamenlijke
    afspraken van WWAP.
  </p>

  <p>
    We bieden arbeidsvoorwaarden volgens de cao Sociaal Werk, aandacht voor
    professionele ontwikkeling en functies waarin je zichtbaar bijdraagt aan de
    zelfstandigheid en het perspectief van jongeren.
  </p>
</section>
